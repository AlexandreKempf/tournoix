<h1 class="mx-4 text-3xl font-bold">Ce tournoi est organisé à profit du téléthon.</h1>

<p class="mx-4">
	Chaque année, le Téléthon mobilise partout en France un formidable élan de solidarité. Pendant 30
	heures, des milliers de bénévoles, de familles, d’associations, d’entreprises et de collectivités
	se rassemblent dans un même objectif : faire avancer la recherche et soutenir les personnes
	touchées par des maladies neuromusculaires et génétiques rares.
</p>

<p class="mx-4">
	Né à l’initiative de l’<a href="https://www.afm-telethon.fr/fr" class="text-green-600"
		>AFM-Téléthon</a
	>, ce mouvement citoyen s’est imposé comme l’un des plus grands événements caritatifs de notre
	pays. Grâce aux dons — qui atteignent chaque année plusieurs dizaines de millions d’euros — le
	Téléthon permet des avancées scientifiques majeures, soutient l’innovation médicale et redonne
	espoir à des milliers de familles.
</p>
<p class="mx-4">
	Participer au Téléthon, c’est contribuer à un mouvement de solidarité unique, où chaque geste
	compte. C’est rejoindre une communauté qui croit que la recherche peut changer le destin.
</p>
